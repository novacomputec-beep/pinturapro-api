// Gera scripts/fixtures/esquema-producao.sql a partir do dump (jsonl) do catálogo de produção:
//   1) túnel aberto (scripts/db-tunnel.md);
//   2) railway run -s Postgres node scripts/rodar-sql-leitura.js scripts/sql/esquema-producao.sql --json | findstr /b "{" > esquema.jsonl
//   3) node scripts/gerar-esquema-producao.js esquema.jsonl scripts/fixtures/esquema-producao.sql DD/MM/AAAA
// Só nomes de tabela/coluna, tipos e DEFAULTs simples — nenhuma linha de dado.
const fs = require('fs')
const [, , entrada, saida, dataDump] = process.argv
const linhas = fs.readFileSync(entrada, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l))
const porTabela = new Map()
for (const l of linhas) { if (!porTabela.has(l.tabela)) porTabela.set(l.tabela, []); porTabela.get(l.tabela).push(l) }
const coluna = (c) => {
  const padrao = c.padrao == null ? null : String(c.padrao)
  if (padrao && /nextval\(/.test(padrao)) return `  "${c.coluna}" ${c.tipo} GENERATED BY DEFAULT AS IDENTITY`
  // NOT NULL só acompanha quem tem DEFAULT: os testes semeiam linhas parciais, e sem default a
  // obrigatoriedade só atrapalharia a semente sem provar nada sobre as consultas.
  return `  "${c.coluna}" ${c.tipo}${padrao ? ` DEFAULT ${padrao}` : ''}${padrao && c.obrigatoria ? ' NOT NULL' : ''}`
}
const partes = [
  `-- ESQUEMA DE PRODUÇÃO (tabelas, colunas, tipos e DEFAULTs) — gerado do catálogo em ${dataDump}, somente leitura,`,
  `-- pelo túnel (scripts/db-tunnel.md). Sem chaves, índices, checks nem dados. Serve aos testes que rodam as`,
  `-- rotas REAIS num Postgres em memória: a consulta falha aqui se usar coluna que a produção não tem.`,
  `-- Regerar depois de migração nova: scripts/gerar-esquema-producao.js.`,
  '',
  '-- Funções que os DEFAULTs de produção chamam (versões mínimas para o teste).',
  "CREATE OR REPLACE FUNCTION uuid_generate_v4() RETURNS uuid LANGUAGE sql AS 'SELECT gen_random_uuid()';",
  "CREATE OR REPLACE FUNCTION gerar_codigo_publico() RETURNS text LANGUAGE sql AS $f$ SELECT string_agg(substr('23456789ABCDEFGHJKMNPQRSTUVWXYZ', 1 + floor(random() * 31)::int, 1), '') FROM generate_series(1, 5) $f$;",
  '',
]
for (const [tabela, cols] of porTabela) partes.push(`CREATE TABLE IF NOT EXISTS "${tabela}" (\n${cols.map(coluna).join(',\n')}\n);`, '')
fs.mkdirSync(require('path').dirname(saida), { recursive: true })
fs.writeFileSync(saida, partes.join('\n'))
console.log(`${porTabela.size} tabelas, ${linhas.length} colunas → ${saida}`)
